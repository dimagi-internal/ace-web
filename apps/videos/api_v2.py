"""Django Ninja v2 router for the workspace-scoped Videos surface.

Mounted under ``/api/w/{workspace_slug}/videos`` from
``apps/api_v2/api.py``. Reads (and a couple of safe writes) are flagged
``x-mcp-expose: True`` so the FastMCP bridge can call them.

The clip-explorer HTML lives at ``out/clip-explorer/<slug>/index.html``
under ``ACE_VIDEOS_ROOT`` — generated by the Node project at
``video-production/connect-videos/``. Django serves it through this
router so the rest of ace-web's session auth + workspace gating apply.
"""
from __future__ import annotations

import logging
from typing import Annotated

from django.conf import settings
from django.http import FileResponse, HttpRequest, HttpResponse, StreamingHttpResponse
from ninja import Path as PathParam
from ninja import Router

from apps.api_v2.auth import session_auth
from apps.api_v2.deps import resolve_workspace_for_member
from apps.api_v2.errors import TYPE_NOT_FOUND, TYPE_VALIDATION, ProblemError

from . import service
from .schemas import (
    ClipEditIn,
    ClipEditOut,
    FeedbackLogOut,
    FeedbackPostIn,
    FeedbackPostOut,
    LibraryEntryOut,
    LibraryOut,
    ProgramCardOut,
    ProgramDetailOut,
    RenderStatusOut,
)

log = logging.getLogger(__name__)

router = Router(auth=session_auth, tags=["videos"])


