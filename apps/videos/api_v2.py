@router.get(
    "/programs/{program_slug}/media/{file_name}",
    summary="Serve an MP4 from the program's explorer media directory (Range-aware)",
)
def serve_media(
    request: HttpRequest,
    workspace_slug: Annotated[str, PathParam()],
    program_slug: Annotated[str, PathParam()],
    file_name: Annotated[str, PathParam()],
) -> HttpResponse | StreamingHttpResponse:
    resolve_workspace_for_member(request, workspace_slug)
    _require_program(workspace_slug, program_slug)

    media_dir = service.explorer_dir(program_slug) / "media"
    try:
        target = (media_dir / file_name).resolve()
        # Reject path traversal: target must stay under media_dir (resolved).
        target.relative_to(media_dir.resolve())
    except (OSError, ValueError):
        raise ProblemError(404, "Not found", type_=TYPE_NOT_FOUND) from None
    if not target.is_file():
        raise ProblemError(404, "Not found", type_=TYPE_NOT_FOUND)

    # FileResponse handles Range-request streaming automatically when the
    # caller sends ``Range: bytes=…``; this is the same code path the
    # browser uses for video scrubbing.
    response = FileResponse(target.open("rb"), as_attachment=False)
    # Hint content type for common video mime — FileResponse guesses from
    # extension but be explicit.
    suffix = target.suffix.lower()
    if suffix in {".mp4", ".m4v"}:
        response["Content-Type"] = "video/mp4"
    elif suffix == ".webm":
        response["Content-Type"] = "video/webm"
    return response


