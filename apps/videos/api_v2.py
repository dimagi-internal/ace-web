@router.get(
    "/programs",
    response=list[ProgramCardOut],
    summary="List video programs in workspace",
    openapi_extra={"x-mcp-expose": True},
)
def list_programs(
    request: HttpRequest,
    workspace_slug: Annotated[str, PathParam()],
) -> list[ProgramCardOut]:
    resolve_workspace_for_member(request, workspace_slug)
    return [
        ProgramCardOut.model_validate(_program_card(r))
        for r in service.list_programs_for_workspace(workspace_slug)
    ]


@router.get(
    "/programs/{program_slug}",
    response=ProgramDetailOut,
    summary="Get a video program's detail payload",
    openapi_extra={"x-mcp-expose": True},
)
def get_program(
    request: HttpRequest,
    workspace_slug: Annotated[str, PathParam()],
    program_slug: Annotated[str, PathParam()],
) -> ProgramDetailOut:
    resolve_workspace_for_member(request, workspace_slug)
    record = _require_program(workspace_slug, program_slug)
    payload = _program_card(record)
    payload["explorer_url"] = _explorer_url(workspace_slug, program_slug)
    # Display the YAML path relative to the parent of ACE_VIDEOS_ROOT
    # (i.e. the directory that contains video-production/). Anchored on
    # ACE_VIDEOS_ROOT rather than BASE_DIR so the path resolves cleanly
    # in tests, in dev, and in prod regardless of where the videos root
    # sits in the tree.
    from pathlib import Path as _Path
    yaml_root = _Path(settings.ACE_VIDEOS_ROOT).parent.parent
    try:
        payload["yaml_path"] = str(record.yaml_path.relative_to(yaml_root))
    except ValueError:
        payload["yaml_path"] = record.yaml_path.name

    return ProgramDetailOut.model_validate(payload)


