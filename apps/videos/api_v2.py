@router.post(
    "/programs/{program_slug}/feedback",
    response=FeedbackPostOut,
    summary="Append a note to the per-program feedback markdown log",
)
def post_feedback(
    request: HttpRequest,
    workspace_slug: Annotated[str, PathParam()],
    program_slug: Annotated[str, PathParam()],
    body: FeedbackPostIn,
) -> FeedbackPostOut:
    import datetime as dt

    resolve_workspace_for_member(request, workspace_slug)
    _require_program(workspace_slug, program_slug)
    ts = dt.datetime.now(dt.UTC).replace(microsecond=0).strftime("%Y-%m-%d %H:%M:%S")
    scope = f"beat:{body.beatId}" if body.scope == "beat" and body.beatId else "global"
    time_bit = f" (video t={body.timestampSec:.1f}s)" if body.timestampSec is not None else ""
    line = f"\n## [{ts}] {scope}{time_bit}\n\n{body.note}\n"
    path = service.feedback_path(program_slug)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(line)
    return FeedbackPostOut(ok=True, timestamp=ts)


@router.post(
    "/programs/{program_slug}/edit",
    response=ClipEditOut,
    summary="Mutate a clip / narration in the program YAML, fire a draft re-render",
)
def post_edit(
    request: HttpRequest,
    workspace_slug: Annotated[str, PathParam()],
    program_slug: Annotated[str, PathParam()],
    body: ClipEditIn,
) -> ClipEditOut:
    resolve_workspace_for_member(request, workspace_slug)
    _require_program(workspace_slug, program_slug)
    result = service.apply_edit(program_slug, body.model_dump(exclude_none=True))
    if not result.ok:
        raise ProblemError(
            400,
            "Edit could not be applied",
            type_=TYPE_VALIDATION,
            detail=result.message,
        )
    needs_hydrate = body.op == "set-clip-asset"
    rerender_triggered = service.trigger_rerender(program_slug, needs_hydrate=needs_hydrate)
    return ClipEditOut(
        ok=True,
        message=result.message + (
            " — re-render kicked off in background" if rerender_triggered
            else " — render already in flight; skipped duplicate"
        ),
        rerender_triggered=rerender_triggered,
    )


