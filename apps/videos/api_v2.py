# Helpers
# ---------------------------------------------------------------------------


def _require_program(workspace_slug: str, program_slug: str) -> service.ProgramRecord:
    """Resolve a program for a workspace member, 404ing on mismatch.

    Slug whitelist runs before any FS access so invalid slugs never reach
    ``programs/`` lookups or subprocess spawns.
    """
    if not service.is_valid_slug(program_slug):
        raise ProblemError(404, "Not found", type_=TYPE_NOT_FOUND)
    record = service.load_program(program_slug)
    if record is None or record.workspace_slug != workspace_slug:
        raise ProblemError(404, "Not found", type_=TYPE_NOT_FOUND)
    return record


def _explorer_url(workspace_slug: str, program_slug: str) -> str:
    return f"/api/w/{workspace_slug}/videos/programs/{program_slug}/explorer.html"


def _program_card(record: service.ProgramRecord) -> dict:
    return {
        "slug": record.slug,
        "name": record.name,
        "tagline": record.tagline,
        "country_focus": record.country_focus,
        "status": record.status,
        "program_url": record.program_url,
        "manifest_count": record.manifest_count,
        "has_explorer_build": record.has_explorer_build,
    }


